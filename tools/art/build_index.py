#!/usr/bin/env python3
"""Sprite Workshop index (Revision 0.105b).

Reads every art_replacements/**/manifest.csv (the source of truth), validates
them (required columns, unique asset_id, unique output file, known statuses
and complexities) and writes art_replacements/INDEX.md: the counts, the
hand-drawing priority list, the first 25 subjects, quick wins and the three
inventory counts. Nothing else is edited by hand in parallel: run this after
changing a manifest.

    python3 tools/art/build_index.py            # validate + write INDEX.md
    python3 tools/art/build_index.py --check    # validate only (exit 1 on problems)
    python3 tools/art/build_index.py --readmes  # also (re)write each folder's README.md

Workload points are relative comparison points (C1=1, C2=3, C3=8, C4=20),
not hours or costs.
"""
import csv
import os
import sys
from collections import Counter, OrderedDict

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "art_replacements")
REQUIRED = ["asset_id", "filename", "display_name", "description", "category", "current_source", "display_width",
            "display_height", "source_width_2x", "source_height_2x", "complexity", "hand_draw_priority", "priority_rank",
            "view_direction", "view_count", "transparent_background", "pivot_or_origin", "replacement_mode",
            "integration_status", "notes"]
STATUSES = ["READY", "ADAPTER_REQUIRED", "REFERENCE_ONLY"]
POINTS = {"C1": 1, "C2": 3, "C3": 8, "C4": 20}


def resolution_class(row):
    side = max(int(row["source_width_2x"]), int(row["source_height_2x"]))
    if side <= 128:
        return "S (<=128 px)"
    if side <= 512:
        return "M (<=512 px)"
    if side <= 1024:
        return "L (<=1024 px)"
    return "XL (>1024 px)"


def load():
    rows, problems, ids, paths = [], [], {}, {}
    for base, _dirs, files in sorted(os.walk(ROOT)):
        if "manifest.csv" not in files:
            continue
        folder = os.path.relpath(base, ROOT)
        with open(os.path.join(base, "manifest.csv"), newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            missing = [c for c in REQUIRED if c not in (reader.fieldnames or [])]
            if missing:
                problems.append(f"{folder}/manifest.csv lacks columns {missing}")
                continue
            for n, row in enumerate(reader, start=2):
                row = {k: (v or "").strip() for k, v in row.items()}
                row["folder"] = folder
                where = f"{folder}/manifest.csv line {n}"
                if row["asset_id"] in ids:
                    problems.append(f"{where}: duplicate asset_id {row['asset_id']} (also {ids[row['asset_id']]})")
                ids[row["asset_id"]] = where
                path = f"{folder}/{row['filename']}"
                if path in paths:
                    problems.append(f"{where}: duplicate output file {path}")
                paths[path] = where
                if row["integration_status"] not in STATUSES:
                    problems.append(f"{where}: unknown integration_status {row['integration_status']}")
                if row["complexity"] not in POINTS:
                    problems.append(f"{where}: unknown complexity {row['complexity']}")
                if not row["filename"].lower().endswith(".png"):
                    problems.append(f"{where}: filename must be a .png")
                for c in ["display_width", "display_height", "source_width_2x", "source_height_2x", "priority_rank", "view_count"]:
                    if not row[c].isdigit():
                        problems.append(f"{where}: {c} must be a whole number")
                rows.append(row)
    return rows, problems


def inventory(rows, key):
    chosen = [r for r in rows if r.get(key) == "yes"]
    subjects = OrderedDict()
    for r in chosen:
        subjects.setdefault(r.get("design_subject") or r["asset_id"], []).append(r)
    drawings = sum(int(r["view_count"]) for r in chosen)
    cx = Counter(r["complexity"] for r in chosen)
    res = Counter(resolution_class(r) for r in chosen)
    points = sum(POINTS[r["complexity"]] * int(r["view_count"]) for r in chosen)
    return {"subjects": len(subjects), "drawings": drawings, "complexity": cx, "resolution": res, "points": points}


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return "\n".join(out)


def write_index(rows):
    by_status = Counter(r["integration_status"] for r in rows)
    folders = OrderedDict()
    for r in rows:
        folders.setdefault(r["folder"], []).append(r)
    ranked = sorted(rows, key=lambda r: int(r["priority_rank"]))
    lines = ["# Sprite Workshop index", "",
             "Generated by `tools/art/build_index.py` from the folders' `manifest.csv` files - do not edit by hand.", "",
             "## Summary", "",
             f"- Registered replacement entries: **{len(rows)}** in **{len(folders)}** folders.",
             f"- **READY** (drop in a PNG and run the game): **{by_status['READY']}**.",
             f"- **ADAPTER_REQUIRED** (catalogued; the game still needs a small adapter for this kind of art): **{by_status['ADAPTER_REQUIRED']}**.",
             f"- **REFERENCE_ONLY** (for art planning; not loaded as a separate PNG in Phase 1): **{by_status['REFERENCE_ONLY']}**.", "",
             "## Folders", "",
             md_table(["Folder", "Entries", "READY", "Adapter", "Reference"],
                      [[f"`{f}/`", len(rs), sum(r["integration_status"] == "READY" for r in rs),
                        sum(r["integration_status"] == "ADAPTER_REQUIRED" for r in rs),
                        sum(r["integration_status"] == "REFERENCE_ONLY" for r in rs)] for f, rs in folders.items()]), "",
             "## The first 25 artwork subjects worth hand-drawing", "",
             "Ranked by visual prominence, time on screen, emotional importance, uniqueness to Little Captain's Hat, reuse and expected benefit (see SPRITE_WORKSHOP_REPORT.md for the reasoning).", "",
             md_table(["#", "What to draw", "Where it appears", "Complexity", "Display (px)", "2x source (px)", "Views", "Status", "File"],
                      [[r["priority_rank"], r["display_name"], r.get("used_in", ""), r["complexity"],
                        f"{r['display_width']}x{r['display_height']}", f"{r['source_width_2x']}x{r['source_height_2x']}",
                        r["view_count"], r["integration_status"], f"`{r['folder']}/{r['filename']}`"] for r in ranked[:25]]), "",
             "## Quick artistic wins", "",
             "Small (C1/C2), READY today and seen often: draw, drop in, run.", "",
             md_table(["What", "2x source (px)", "File"],
                      [[r["display_name"], f"{r['source_width_2x']}x{r['source_height_2x']}", f"`{r['folder']}/{r['filename']}`"]
                       for r in ranked if r["integration_status"] == "READY" and r["complexity"] in ("C1", "C2")
                       and r["hand_draw_priority"] in ("high", "medium")][:12]), "",
             "## Inventory counts", "",
             "A = absolute reusable minimum (smallest sensible set of distinct designs, with legitimate reuse); "
             "B = practical illustrated set; C = full distinct-object set (every meaningfully distinct in-world object; "
             "no animation frames, no UI-only pictures, no bespoke per-harbour landmarks). Points: C1=1, C2=3, C3=8, C4=20 per drawing (relative, not hours).", ""]
    inv = {k: inventory(rows, k) for k in ("set_a", "set_b", "set_c")}
    lines.append(md_table(["", "A minimum", "B practical", "C full"], [
        ["Unique design subjects"] + [inv[k]["subjects"] for k in inv],
        ["Static drawings (views)"] + [inv[k]["drawings"] for k in inv],
        ["C1 / C2 / C3 / C4"] + [" / ".join(str(inv[k]["complexity"].get(c, 0)) for c in POINTS) for k in inv],
        ["Resolution S / M / L / XL"] + [" / ".join(str(sum(v for kk, v in inv[k]["resolution"].items() if kk.startswith(p))) for p in "SMLX") for k in inv],
        ["Relative workload (points)"] + [inv[k]["points"] for k in inv]]))
    lines += ["", "## Full priority list", "",
              md_table(["#", "asset_id", "Priority", "Complexity", "Status"],
                       [[r["priority_rank"], f"`{r['asset_id']}`", r["hand_draw_priority"], r["complexity"], r["integration_status"]] for r in ranked]), ""]
    with open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return by_status, inv


README = """# {title}

{what}

## What belongs here

{entries}

## How to draw a replacement

1. Pick a row in `manifest.csv` (open it in any spreadsheet program or text editor).
2. Draw the picture at the **2x source size** (`source_width_2x` x `source_height_2x` pixels). The game shows it at about half that size
   (`display_width` x `display_height` on the 1600 x 900 screen), so 2x keeps lines crisp. Keep the shape (aspect ratio) exactly;
   any size from half to four times the 2x size is accepted, but other shapes are refused.
3. Save it as a **PNG with a transparent background** under exactly the `filename` in the row, in **this folder**.
4. Open the project in Godot (it imports the new file by itself) and run the game. The picture is used wherever that thing appears.

## Style

Warm, hand-illustrated, soft outlines, gentle colours like the rest of Little Captain's Hat; seen {view}.

## Orientation, pivot and what must not change

{orientation}

The picture never changes the game itself: walkable deck, collisions, interaction spots, the pet's safe places, routes, anchorages,
fish data and saves come from the game's own data, not from the art.

## Status of the entries

- **READY**: drop in the PNG and it is used.
- **ADAPTER_REQUIRED**: catalogued, but this kind of art is drawn in code with movement or states; the game needs a small adapter before a PNG can replace it. Drawing it now is still useful.
- **REFERENCE_ONLY**: for planning (part of a larger picture, or a light/effect); not loaded on its own.

{adapters}

## Testing a replacement

- Run the game and look at the thing. If it does not change: check the file name and that `integration_status` is READY.
- A wrong shape or an unreadable file is ignored: the original art stays, and Godot's Output panel says
  `Sprite Workshop: ...` with the reason.
- Missing PNG: the game keeps its own art. Remove (or rename) your PNG to get the original back.
- Changes are picked up when the game starts; restart the game after adding or changing a PNG.
"""

