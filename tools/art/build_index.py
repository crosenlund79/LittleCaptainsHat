def write_readmes(rows):
    folders = OrderedDict()
    for r in rows:
        folders.setdefault(r["folder"], []).append(r)
    for folder, rs in folders.items():
        top = folder.split("/")[0]
        what, view, orientation = FOLDER_TEXT[top]
        entries = "\n".join(f"- `{r['filename']}` - {r['display_name']} ({r['integration_status']}; {r['source_width_2x']} x {r['source_height_2x']} px; "
                            f"replaces: {r['current_source']})" for r in rs)
        adapters = [r for r in rs if r["integration_status"] == "ADAPTER_REQUIRED"]
        adapter_text = ("Still needing adapters here: " + ", ".join(f"`{r['filename']}`" for r in adapters) + ".") if adapters else "Nothing in this folder needs an adapter."
        with open(os.path.join(ROOT, folder, "README.md"), "w", encoding="utf-8") as f:
            f.write(README.format(title=folder, what=what, entries=entries, view=view, orientation=orientation, adapters=adapter_text))


def main():
    rows, problems = load()
    for p in problems:
        print("PROBLEM:", p)
    if "--check" in sys.argv:
        sys.exit(1 if problems else 0)
    if problems:
        sys.exit(1)
    if "--readmes" in sys.argv:
        write_readmes(rows)
    by_status, inv = write_index(rows)
    print(f"{len(rows)} entries: " + ", ".join(f"{k} {v}" for k, v in by_status.items()))
    for k, v in inv.items():
        print(f"  {k}: {v['subjects']} subjects, {v['drawings']} drawings, {v['points']} points")


if __name__ == "__main__":
    main()
